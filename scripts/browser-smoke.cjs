const { chromium } = require('../.tools/browser/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true});
 try {
 const page = await browser.newPage({viewport:{width:1440,height:1050}});
 const errors=[];
 page.on('pageerror', e=>errors.push(e.message));
 const base=process.env.COMPANION_TEST_URL || 'http://127.0.0.1:8091';
 await page.goto(base+'/login');
 assert.deepEqual(await page.locator('[name=profile] option').evaluateAll(options=>options.map(o=>o.value)),['DEMO'],'requires demo mode');
 await page.getByRole('button',{name:'연결',exact:true}).click();
 await page.getByRole('button',{name:'새로 고침',exact:true}).click();
 assert.match(await page.locator('body').innerText(),/companion-api/);
 await page.screenshot({path:'.tools/catalog.png',fullPage:true});
 await page.getByRole('link',{name:'소스',exact:true}).click();
 const external=page.locator('form').filter({has:page.locator('select[name=provider]')});
 await external.locator('[name=name]').fill('browser-test');
 await external.locator('[name=url]').fill('https://github.com/devmrko/db-companion');
 await external.getByRole('button',{name:'등록',exact:true}).click();
 assert.match(await page.locator('body').innerText(),/browser-test/);
 const oci=page.locator('form').filter({has:page.locator('select[name=resourceId]')});
 await oci.locator('[name=resourceId]').selectOption('demo-repository');
 await oci.getByRole('button',{name:'등록',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'등록 해제',exact:true}).count(),2);
 await page.screenshot({path:'.tools/sources.png',fullPage:true});
 await page.locator('.scope-bar [name=region]').selectOption('us-ashburn-1');
 await page.locator('.scope-bar').getByRole('button',{name:'적용',exact:true}).click();
 assert.match(await page.locator('body').innerText(),/조회 이력 없음/);
 await page.getByRole('link',{name:'소스',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'등록 해제',exact:true}).count(),0);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'mobile overflow');
 await page.screenshot({path:'.tools/catalog-mobile.png',fullPage:true});
 await page.getByRole('link',{name:'OCI 사용 안내',exact:true}).click();
 assert.equal(await page.locator('article.guide').count(),6);
 await page.getByRole('button',{name:'연결 해제',exact:true}).click();
 assert.match(page.url(),/\/login$/);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'passed',checks:['profile','catalog refresh','OCI/GitHub registration','region isolation','help','390px layout','logout','JS errors']}));
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1)});
