const { chromium } = require('../.tools/browser/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:1050}});
 const errors=[];
 page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8091/login');
 assert.deepEqual(await page.locator('[name=profile] option').evaluateAll(options=>options.map(o=>o.value)),['DEMO'],'smoke test requires demo mode');
 await page.screenshot({path:'.tools/login.png',fullPage:true});
 await page.getByRole('button',{name:'연결',exact:true}).click();
 assert.match(await page.locator('.banner.demo').innerText(),/실제 OCI 연결/);
 await page.getByRole('link',{name:'＋ 프로젝트 등록'}).click();
 await page.locator('[name=name]').fill('DB Companion');
 await page.locator('[name=repositoryUrl]').fill('https://github.com/devmrko/db-companion');
 await page.getByRole('button',{name:'프로젝트 저장'}).click();
 const project=page.url();
 await page.locator('form').filter({has:page.locator('[name=kind][value=BUILD]')}).locator('[name=acknowledged]').check();
 await page.getByRole('button',{name:'빌드·테스트 실행',exact:true}).click();
 await page.getByRole('button',{name:'상태 갱신'}).click();
 assert.match(await page.locator('body').innerText(),/DEMO_SUCCEEDED/);
 await page.screenshot({path:'.tools/project.png',fullPage:true});
 await page.getByRole('link',{name:'OCI 파이프라인 조회'}).click();
 assert.match(await page.locator('body').innerText(),/demo-vm/);
 await page.goto(project);
 await page.locator('form').filter({has:page.locator('[name=kind][value=DEPLOY]')}).locator('[name=acknowledged]').check();
 await page.getByRole('button',{name:'VM 배포 실행',exact:true}).click();
 assert.match(await page.locator('body').innerText(),/DEMO_ACCEPTED/);
 await page.getByRole('link',{name:'OCI 사용 안내',exact:true}).click();
 assert.equal(await page.locator('article.guide').count(),6);
 await page.setViewportSize({width:390,height:844});
 await page.goto(project);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 assert.equal(overflow,false,'mobile page overflow');
 await page.screenshot({path:'.tools/mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'passed',project,checks:['login','project create','build','refresh','VM demo deploy','pipeline list','six guides','mobile overflow','JS errors']}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
